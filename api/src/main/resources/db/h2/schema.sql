-- Pessoa que usa o app (cidadão) ou opera a plataforma (administrador).
CREATE TABLE TB_CT_USUARIO (
    id_usuario     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    nm_usuario     VARCHAR2(100) NOT NULL,
    ds_email       VARCHAR2(120) NOT NULL,
    ds_senha_hash  VARCHAR2(100) NOT NULL,
    tp_perfil      VARCHAR2(10)  DEFAULT 'CIDADAO' NOT NULL,
    dt_cadastro    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_ct_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_ct_usuario_email UNIQUE (ds_email),
    CONSTRAINT ck_ct_usuario_perfil CHECK (tp_perfil IN ('CIDADAO', 'ADMIN'))
);

-- Preferências de acessibilidade (1:1 com usuário).
CREATE TABLE TB_CT_PREFERENCIA (
    id_usuario           NUMBER(10) NOT NULL,
    fl_evitar_escadas    NUMBER(1)  DEFAULT 1 NOT NULL,
    fl_priorizar_rampas  NUMBER(1)  DEFAULT 1 NOT NULL,
    fl_alertas_visuais   NUMBER(1)  DEFAULT 1 NOT NULL,
    fl_alto_contraste    NUMBER(1)  DEFAULT 0 NOT NULL,
    CONSTRAINT pk_ct_preferencia PRIMARY KEY (id_usuario),
    CONSTRAINT fk_ct_pref_usuario FOREIGN KEY (id_usuario) REFERENCES TB_CT_USUARIO (id_usuario) ON DELETE CASCADE,
    CONSTRAINT ck_ct_pref_escadas  CHECK (fl_evitar_escadas   IN (0, 1)),
    CONSTRAINT ck_ct_pref_rampas   CHECK (fl_priorizar_rampas IN (0, 1)),
    CONSTRAINT ck_ct_pref_alertas  CHECK (fl_alertas_visuais  IN (0, 1)),
    CONSTRAINT ck_ct_pref_contraste CHECK (fl_alto_contraste  IN (0, 1))
);

-- Local público consultado pelo cidadão.
CREATE TABLE TB_CT_LOCAL (
    id_local            VARCHAR2(40)  NOT NULL,
    nm_local            VARCHAR2(100) NOT NULL,
    ds_categoria        VARCHAR2(50)  NOT NULL,
    ds_endereco         VARCHAR2(150) NOT NULL,
    st_acessibilidade   VARCHAR2(12)  NOT NULL,
    ds_resumo           VARCHAR2(400),
    ds_confianca        VARCHAR2(60)  DEFAULT 'Cadastro local' NOT NULL,
    nr_ocupacao         NUMBER(6)     DEFAULT 0 NOT NULL,
    dt_ultima_leitura   TIMESTAMP,
    CONSTRAINT pk_ct_local PRIMARY KEY (id_local),
    CONSTRAINT ck_ct_local_status CHECK (st_acessibilidade IN ('ACESSIVEL', 'PARCIAL', 'INACESSIVEL')),
    CONSTRAINT ck_ct_local_ocupacao CHECK (nr_ocupacao >= 0)
);

-- Recursos de acessibilidade e obstáculos cadastrados de cada local (N:1 com local).
CREATE TABLE TB_CT_ITEM_ACESSIBILIDADE (
    id_item    NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    id_local   VARCHAR2(40)  NOT NULL,
    tp_item    VARCHAR2(10)  NOT NULL,
    ds_item    VARCHAR2(150) NOT NULL,
    CONSTRAINT pk_ct_item PRIMARY KEY (id_item),
    CONSTRAINT fk_ct_item_local FOREIGN KEY (id_local) REFERENCES TB_CT_LOCAL (id_local) ON DELETE CASCADE,
    CONSTRAINT ck_ct_item_tipo CHECK (tp_item IN ('RECURSO', 'OBSTACULO'))
);

-- Relato de barreira feito por um cidadão sobre um local.
CREATE TABLE TB_CT_OCORRENCIA (
    id_ocorrencia   NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 1100) NOT NULL,
    id_usuario      NUMBER(10)    NOT NULL,
    id_local        VARCHAR2(40)  NOT NULL,
    ds_categoria    VARCHAR2(40)  NOT NULL,
    ds_descricao    VARCHAR2(500) NOT NULL,
    st_ocorrencia   VARCHAR2(12)  DEFAULT 'RECEBIDA' NOT NULL,
    dt_criacao      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    dt_atualizacao  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_ct_ocorrencia PRIMARY KEY (id_ocorrencia),
    CONSTRAINT fk_ct_ocor_usuario FOREIGN KEY (id_usuario) REFERENCES TB_CT_USUARIO (id_usuario),
    CONSTRAINT fk_ct_ocor_local FOREIGN KEY (id_local) REFERENCES TB_CT_LOCAL (id_local),
    CONSTRAINT ck_ct_ocor_status CHECK (st_ocorrencia IN ('RECEBIDA', 'EM_ANALISE', 'ENCAMINHADA', 'RESOLVIDA')),
    CONSTRAINT ck_ct_ocor_descricao CHECK (LENGTH(ds_descricao) >= 12)
);

-- Sensor IoT (simulado) instalado em um local.
CREATE TABLE TB_CT_SENSOR (
    id_sensor          NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    cd_sensor          VARCHAR2(30) NOT NULL,
    tp_sensor          VARCHAR2(10) NOT NULL,
    id_local           VARCHAR2(40) NOT NULL,
    ds_unidade         VARCHAR2(10) NOT NULL,
    vl_limite_alerta   NUMBER(8,2)  NOT NULL,
    fl_ativo           NUMBER(1)    DEFAULT 1 NOT NULL,
    CONSTRAINT pk_ct_sensor PRIMARY KEY (id_sensor),
    CONSTRAINT uk_ct_sensor_codigo UNIQUE (cd_sensor),
    CONSTRAINT uk_ct_sensor_tipo_local UNIQUE (tp_sensor, id_local),
    CONSTRAINT fk_ct_sensor_local FOREIGN KEY (id_local) REFERENCES TB_CT_LOCAL (id_local),
    CONSTRAINT ck_ct_sensor_tipo CHECK (tp_sensor IN ('OCUPACAO', 'CHUVA')),
    CONSTRAINT ck_ct_sensor_limite CHECK (vl_limite_alerta > 0),
    CONSTRAINT ck_ct_sensor_ativo CHECK (fl_ativo IN (0, 1))
);

-- Leitura enviada por um sensor (N:1 com sensor).
CREATE TABLE TB_CT_LEITURA_SENSOR (
    id_leitura    NUMBER(12)   GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    id_sensor     NUMBER(10)   NOT NULL,
    vl_leitura    NUMBER(10,2) NOT NULL,
    dt_leitura    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fl_simulada   NUMBER(1)    DEFAULT 1 NOT NULL,
    CONSTRAINT pk_ct_leitura PRIMARY KEY (id_leitura),
    CONSTRAINT fk_ct_leitura_sensor FOREIGN KEY (id_sensor) REFERENCES TB_CT_SENSOR (id_sensor),
    CONSTRAINT ck_ct_leitura_valor CHECK (vl_leitura >= 0),
    CONSTRAINT ck_ct_leitura_simulada CHECK (fl_simulada IN (0, 1))
);

-- Alerta gerado quando uma leitura ultrapassa o limite do sensor (1:1 com a leitura que o disparou).
CREATE TABLE TB_CT_ALERTA (
    id_alerta       NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 300) NOT NULL,
    id_leitura      NUMBER(12)    NOT NULL,
    tp_alerta       VARCHAR2(20)  NOT NULL,
    ds_titulo       VARCHAR2(120) NOT NULL,
    ds_descricao    VARCHAR2(400) NOT NULL,
    st_alerta       VARCHAR2(10)  DEFAULT 'ATIVO' NOT NULL,
    dt_criacao      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    dt_encerramento TIMESTAMP,
    CONSTRAINT pk_ct_alerta PRIMARY KEY (id_alerta),
    CONSTRAINT uk_ct_alerta_leitura UNIQUE (id_leitura),
    CONSTRAINT fk_ct_alerta_leitura FOREIGN KEY (id_leitura) REFERENCES TB_CT_LEITURA_SENSOR (id_leitura),
    CONSTRAINT ck_ct_alerta_status CHECK (st_alerta IN ('ATIVO', 'ENCERRADO'))
);

CREATE INDEX ix_ct_ocor_usuario ON TB_CT_OCORRENCIA (id_usuario);
CREATE INDEX ix_ct_ocor_local ON TB_CT_OCORRENCIA (id_local);
CREATE INDEX ix_ct_leitura_sensor_dt ON TB_CT_LEITURA_SENSOR (id_sensor, dt_leitura);

